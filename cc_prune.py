def cmd_audit(args) -> None:
    recs = load(args.path)
    uses = {}
    for i, r in enumerate(recs):
        for b in blocks(r):
            if b.get("type") == "tool_use" and b.get("id"):
                uses[b["id"]] = (i, b.get("name", "?"), b.get("input", {}))

    def all_text(rec):
        out = []

        def walk(v):
            if isinstance(v, str):
                out.append(v)
            elif isinstance(v, dict):
                for x in v.values():
                    walk(x)
            elif isinstance(v, list):
                for x in v:
                    walk(x)
        walk(rec)
        return "\n".join(out)

    for tgt in args.lines:
        if tgt >= len(recs):
            print(f"\n### line {tgt}: out of range ({len(recs)} records)")
            continue
        tr = next((b for b in blocks(recs[tgt])
                   if b.get("type") == "tool_result"), None)
        if tr is None:
            print(f"\n### line {tgt}: no tool_result here")
            continue

        text = result_text(tr)
        uline, tool, params = uses.get(tr.get("tool_use_id"), (None, "?", {}))
        print("=" * 70)
        print(f"### line {tgt} | {len(text):,} chars | {tool}"
              + (" | IMAGE" if is_image_result(tr) else ""))
        print(f"    call at line {uline}: "
              f"{json.dumps(params, ensure_ascii=False)[:240]}")

        verdict = []
        src = params.get("file_path") or params.get("path")
        if src:
            exists = os.path.exists(src)
            print(f"\n[disk]    {src}\n          exists: {exists}"
                  + (f"  ({os.path.getsize(src):,} B)" if exists else ""))
            verdict.append("SAFE: re-readable" if exists else "RISK: file is gone")
            rereads = [i2 for (i2, _, p2) in uses.values()
                       if i2 > tgt and (p2.get("file_path") or p2.get("path")) == src]
            print(f"[reread]  read again at: {rereads or 'never'}")
            if rereads:
                verdict.append("SAFE: superseded")
            base = os.path.basename(src)
            later = [i for i in range(tgt + 1, len(recs)) if base in all_text(recs[i])]
            print(f"[mention] '{base}' in {len(later)} later records"
                  + (f", e.g. {later[:8]}" if later else ""))
            if len(later) > 20:
                verdict.append("RISK: still an active topic")
            elif not later:
                verdict.append("SAFE: never referenced again")
        else:
            cmd = params.get("command")
            print(f"\n[disk]    not a file read"
                  + (f"; command: {str(cmd)[:150]}" if cmd else ""))
            verdict.append("CHECK: output exists only here unless re-runnable")

        for j in range(tgt + 1, min(tgt + 6, len(recs))):
            said = " ".join(b.get("text", "") for b in blocks(recs[j])
                            if b.get("type") == "text").strip()
            if said:
                print(f"\n[after]   line {j}: {said[:340]}")
                break
        print(f"\n[head]    {text[:220]!r}")
        print(f"\n>> {' | '.join(verdict)}")
    print("=" * 70)


